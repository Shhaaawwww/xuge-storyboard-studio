const dictionaries: Record<Locale, Record<TranslationKey, string>> = { "zh-CN": zh, "en-US": en };
const storageKey = "xuge.locale";

function detectLocale(): Locale {
  const stored = window.localStorage.getItem(storageKey);
  if (stored === "zh-CN" || stored === "en-US") return stored;
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

function interpolate(template: string, values?: Record<string, string | number>) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`));
}

export function translate(locale: Locale, key: TranslationKey, values?: Record<string, string | number>) {
  return interpolate(dictionaries[locale][key], values);
}

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(detectLocale);

  useEffect(() => {
    window.localStorage.setItem(storageKey, locale);
    document.documentElement.lang = locale;
    document.title = dictionaries[locale]["meta.title"];
  }, [locale]);

  const t = useCallback((key: TranslationKey, values?: Record<string, string | number>) => (
    translate(locale, key, values)
  ), [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export function LanguageSwitch() {
  const { locale, setLocale, t } = useI18n();
  return (
    <div className="language-switch" role="group" aria-label={t("language.label")}>
      <button className={locale === "zh-CN" ? "active" : ""} onClick={() => setLocale("zh-CN")} aria-pressed={locale === "zh-CN"}>{t("language.zh")}</button>
      <button className={locale === "en-US" ? "active" : ""} onClick={() => setLocale("en-US")} aria-pressed={locale === "en-US"}>{t("language.en")}</button>
    </div>
  );
}
